/**
 * The world the scenarios of US04 and US21 start from, signed in with real session tokens (TS03):
 * a university of its own, a tutor free tomorrow from nine to twelve, Lima time, and two students,
 * Ana and Bruno, each with credits to book.
 *
 * <p>Every request carries {@code Authorization: Bearer} and passes the real access filter, so the
 * person is the one of the token and nobody else can be named. The hours are generated by the tutor
 * declaring their availability and booked by the students holding and confirming them, all over
 * HTTP. Identity, wallet, sessions and booking are the real thing; skills is the seam, mocked with
 * the answers the real module gives, since enabling a tutor is a story of its own.
 *
 * <p>The clock starts at noon in Lima, as {@link BookingScenario}'s does, so a scenario that moves
 * it by minutes or days never depends on the hour of the build.
 */
@SpringBootTest(properties = "ayni.test.identity-headers=false")
@AutoConfigureMockMvc
@Import(BookingTestConfig.class)
abstract class SignedInBookingScenario {

  @ServiceConnection
  static final PostgreSQLContainer<?> POSTGRES = BookingTestDatabase.INSTANCE;

  protected static final ZoneId LIMA = ZoneId.of("America/Lima");

  protected final UUID subject = UUID.randomUUID();

  @Autowired protected MockMvc mockMvc;
  @Autowired protected JdbcTemplate jdbc;
  @Autowired protected MutableClock clock;
  @Autowired protected WalletApi wallet;
  @Autowired private TenantRepository tenants;
  @Autowired private UserRepository users;
  @Autowired private UserSessionRepository userSessions;
  @Autowired private AccessTokenGenerator tokens;
  @MockitoBean protected SkillsApi skills;

  protected String tenant;
  protected Person tutor;
  protected Person ana;
  protected Person bruno;
  protected SignedInPeople people;

  @BeforeEach
  void aTutorFreeTomorrowMorning() throws Exception {
    clock.set(BookingScenario.middayInLima(Instant.now()));
    people = new SignedInPeople(tenants, users, userSessions, tokens);
    tenant = people.aUniversity("A");
    tutor = people.aStudent(tenant);
    ana = people.aStudent(tenant);
    bruno = people.aStudent(tenant);

    when(skills.enabledSkillsOf(tutor.id())).thenReturn(List.of(subject));
    when(skills.isTutorEnabledFor(tutor.id(), subject)).thenReturn(true);
    when(skills.requireItem(subject))
        .thenReturn(new CatalogItemView(subject, CatalogScope.UNIVERSITY, "Databases I", "1ASI0616"));

    String weekday = today().plusDays(1).getDayOfWeek().name();
    mockMvc
        .perform(
            as(tutor, post("/api/v1/tutor/availability"))
                .contentType(MediaType.APPLICATION_JSON)
                .content(
                    """
                    {"dayOfWeek":"%s","startsAtTime":"09:00:00","endsAtTime":"12:00:00",
                     "validFrom":"%s"}
                    """
                        .formatted(weekday, today())))
        .andExpect(status().isCreated());
    grant(ana, 10);
    grant(bruno, 10);
  }

  protected LocalDate today() {
    return LocalDate.now(clock.withZone(LIMA));
  }

  /** Tomorrow at that hour, Lima time, as the instant the API speaks in. */
  protected Instant tomorrowAt(int hour) {
    return ZonedDateTime.of(today().plusDays(1), LocalTime.of(hour, 0), LIMA).toInstant();
  }

  /** The request, signed in as that person. */
  protected MockHttpServletRequestBuilder as(Person person, MockHttpServletRequestBuilder request) {
    return request.header("Authorization", "Bearer " + person.token());
  }

  /** Holds and books those hours of the tutor for the student, as the student does; the booking. */
  protected UUID book(Person student, Instant start, int hours, String need) throws Exception {
    mockMvc
        .perform(
            as(student, post("/api/v1/bookings/holds"))
                .contentType(MediaType.APPLICATION_JSON)
                .content(
                    """
                    {"tutorId":"%s","start":"%s","hours":%d}
                    """
                        .formatted(tutor.id(), start, hours)))
        .andExpect(status().isCreated());
    String booked =
        mockMvc
            .perform(
                as(student, post("/api/v1/bookings"))
                    .contentType(MediaType.APPLICATION_JSON)
                    .content(
                        """
                        {"tutorId":"%s","catalogItemId":"%s","start":"%s","hours":%d,
                         "needDescription":"%s"}
                        """
                            .formatted(tutor.id(), subject, start, hours, need)))
            .andExpect(status().isCreated())
            .andReturn()
            .getResponse()
            .getContentAsString();
    return UUID.fromString(JsonPath.read(booked, "$.id"));
  }

  /** Moves the clock, as the passing of time does. */
  protected void advance(Duration duration) {
    clock.set(clock.instant().plus(duration));
  }

  private void grant(Person student, int credits) {
    TenantContext.runAs(
        tenant,
        () ->
            wallet.grant(
                student.id(), Credits.of(credits), CreditType.EARNED, null, UUID.randomUUID()));
  }
}
