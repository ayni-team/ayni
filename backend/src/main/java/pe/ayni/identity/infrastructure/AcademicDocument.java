package pe.ayni.identity.infrastructure;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import pe.ayni.identity.application.AcademicStatus;

/**
 * The document of one university in the simulated academic system (ADR 0006), schema version 1:
 * who the university is, its careers, its curriculum and its students.
 *
 * <p>Generated by {@code tools/academic-data/generate.py}, which describes the schema. A student's
 * approved course names the course by its code only; its name is the one of the curriculum.
 *
 * <p>{@link #checkCoherence} is what makes a document usable, and the adapter asks it of every
 * document it reads. Its messages say which rule was broken and never which student broke it, since
 * they end in the log of the platform.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
record AcademicDocument(
        University university,
        List<String> careers,
        List<Course> courses,
        List<Student> students) {

    AcademicDocument {
        careers = careers == null ? List.of() : List.copyOf(careers);
        courses = courses == null ? List.of() : List.copyOf(courses);
        students = students == null ? List.of() : List.copyOf(students);
    }

    /** Who the university is. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    record University(
            String code,
            String name,
            String logoUrl,
            String primaryColor,
            String secondaryColor,
            List<String> emailDomains,
            String timezone,
            BigDecimal minimumTeachingGrade,
            String currentTerm) {}

    /** A course of the curriculum, once however many careers share it. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    record Course(String code, String name, List<Placement> careers) {}

    /** The cycle a course is taught in, in one career. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    record Placement(String career, Integer cycle) {}

    /** One student as the university's academic system keeps them. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    record Student(
            String email,
            String studentCode,
            String fullName,
            String career,
            Integer cycle,
            String currentTerm,
            String status,
            List<ApprovedCourse> approvedCourses) {

        List<ApprovedCourse> approved() {
            return approvedCourses == null ? List.of() : approvedCourses;
        }
    }

    /** A course the student approved, by its code, with the grade and the term. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    record ApprovedCourse(String courseCode, BigDecimal grade, String term) {}

    /**
     * This document with the students of a local addition (its other fields are ignored): they are
     * added to the ones of the document, and one whose email is in both is the local one.
     */
    AcademicDocument withLocalStudents(List<Student> local) {
        if (local == null || local.isEmpty()) {
            return this;
        }
        Map<String, Student> byEmail = new LinkedHashMap<>();
        for (Student student : students) {
            byEmail.put(keyOf(student.email()), student);
        }
        for (Student student : local) {
            byEmail.remove(keyOf(student.email()));
            byEmail.put(keyOf(student.email()), student);
        }
        return new AcademicDocument(university, careers, courses, new ArrayList<>(byEmail.values()));
    }

    /** The student with that institutional email, whatever its case. */
    Optional<Student> student(String email) {
        String wanted = keyOf(email);
        return students.stream().filter(student -> keyOf(student.email()).equals(wanted)).findFirst();
    }

    /** The name the curriculum gives that course code. */
    String courseName(String code) {
        return courses.stream()
                .filter(course -> course.code().equals(code))
                .map(Course::name)
                .findFirst()
                .orElseThrow(() -> new Incoherent("an approved course is not in the curriculum"));
    }

    /**
     * Refuses a document that does not agree with itself or is not of that university.
     *
     * @param code the university the document was read for, in upper case
     * @throws Incoherent naming the rule that was broken
     */
    void checkCoherence(String code) {
        checkUniversity(code);

        Map<String, Set<String>> careersOfCourse = new HashMap<>();
        for (Course course : courses) {
            require(present(course.code()), "a course has no code");
            require(present(course.name()), "a course has no name");
            require(
                    careersOfCourse.put(course.code(), new HashSet<>()) == null,
                    "a course code is repeated");
            require(
                    course.careers() != null && !course.careers().isEmpty(),
                    "a course belongs to no career");
            for (Placement placement : course.careers()) {
                require(
                        present(placement.career()) && placement.cycle() != null && placement.cycle() > 0,
                        "a course has a career without a name or a cycle");
                careersOfCourse.get(course.code()).add(placement.career());
            }
        }

        List<String> domains =
                university.emailDomains().stream().map(AcademicDocument::keyOf).toList();
        Set<String> emails = new HashSet<>();
        Set<String> studentCodes = new HashSet<>();
        for (Student student : students) {
            require(present(student.email()), "a student has no email");
            require(present(student.studentCode()), "a student has no student code");
            require(present(student.fullName()), "a student has no name");
            require(present(student.career()), "a student has no career");
            require(present(student.currentTerm()), "a student has no current term");
            require(student.cycle() == null || student.cycle() > 0, "a student has a cycle below 1");
            require(statusOf(student) != null, "a student has a status that is not known");
            require(emails.add(keyOf(student.email())), "a student email is repeated");
            require(studentCodes.add(student.studentCode().trim()), "a student code is repeated");
            require(
                    domains.contains(domainOf(student.email())),
                    "a student email is not of a domain of the university");
            for (ApprovedCourse approved : student.approved()) {
                require(
                        present(approved.courseCode()) && approved.grade() != null && present(approved.term()),
                        "an approved course has no code, grade or term");
                Set<String> careersOfIt = careersOfCourse.get(approved.courseCode());
                require(
                        careersOfIt != null && careersOfIt.contains(student.career()),
                        "an approved course is not in the curriculum of the student's career");
            }
        }
    }

    private void checkUniversity(String code) {
        require(university != null, "the document has no university");
        require(code.equals(keyOf(university.code()).toUpperCase(Locale.ROOT)), "the document is of another university");
        require(present(university.name()), "the university has no name");
        require(
                university.emailDomains() != null
                        && !university.emailDomains().isEmpty()
                        && university.emailDomains().stream().allMatch(AcademicDocument::present),
                "the university has no email domain");
        require(present(university.timezone()), "the university has no time zone");
        require(university.minimumTeachingGrade() != null, "the university has no minimum teaching grade");
        require(present(university.currentTerm()), "the university has no current term");
    }

    /** The status of the student, {@code null} when it is not one the platform knows. */
    static AcademicStatus statusOf(Student student) {
        if (student.status() == null) {
            return null;
        }
        try {
            return AcademicStatus.valueOf(student.status().trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException unknown) {
            return null;
        }
    }

    private static String domainOf(String email) {
        String key = keyOf(email);
        return key.substring(key.lastIndexOf('@') + 1);
    }

    private static String keyOf(String value) {
        return value == null ? "" : value.trim().toLowerCase(Locale.ROOT);
    }

    private static boolean present(String value) {
        return value != null && !value.isBlank();
    }

    private static void require(boolean condition, String brokenRule) {
        if (!condition) {
            throw new Incoherent(brokenRule);
        }
    }

    /** The document breaks one of its rules: a mistake of the platform, not of the person asking. */
    static final class Incoherent extends RuntimeException {

        Incoherent(String brokenRule) {
            super(brokenRule);
        }
    }
}
